package com.flyingcode.problem;

/**
 * 省份数量 - 纯并查集版
 * 使用并查集(Union-Find)统计图中连通分量的个数.
 *
 * 算法设计思路:
 * 1. 初始化并查集: 每个城市的父节点指向自身，即每个城市自成一个独立的集合
 * 2. 遍历邻接矩阵: 对每对相连的城市执行合并操作，将它们放入同一个集合中
 * 3. 统计根节点数量: 最终并查集中有多少个不同的根节点，就有多少个省份
 *
 * 算法复杂度分析:
 * - 时间复杂度: O(n^2 * α(n))，其中n是城市数量，α(n)是反Ackermann函数。
 *   外层双重循环遍历邻接矩阵(O(n^2))，并查集的find和union操作接近O(1)，
 *   因为α(n)增长极慢(对于所有实际n，α(n) ≤ 5)。
 * - 空间复杂度: O(n)，只使用了一个长度为n的parent数组。
 *
 * 并查集核心思想:
 * - find操作: 查找元素所属集合的根节点，使用路径压缩优化
 * - union操作: 将两个不同集合合并，将一个集合的根节点指向另一个集合的根节点
 * - 路径压缩: 在查找过程中将沿途节点直接连接到根节点，减少后续查找时间
 *
 * 与原版对比:
 * - 移除了冗余的BFS遍历和visited数组
 * - 直接遍历邻接矩阵的边进行合并，真正发挥并查集的优势
 * - 不需要显式遍历图，通过合并和查找即可确定连通分量
 */
public class Algo030ProvinceCountUFPure {

  /**
   * 计算省份数量，使用并查集统计图中连通分量的个数.
   *
   * 该方法通过初始化并查集，遍历邻接矩阵合并相连的城市，
   * 最后统计并查集中根节点的数量，即省份数量.
   *
   * @param isConnected 表示城市之间连接关系的n*n维邻接矩阵，
   *                    isConnected[i][j] = 1 表示城市i和城市j直接相连，
   *                    isConnected[i][j] = 0 表示不相连
   * @return 省份数量，即图中连通分量的个数
   */
  public int solution(int[][] isConnected) {
    // 边界条件检查: 空矩阵或null输入直接返回0个省份
    if (isConnected == null || isConnected.length == 0) {
      return 0;
    }

    // 城市数量
    int n = isConnected.length;
    // 并查集数组，parent[i] 存储城市i的父节点
    int[] parent = new int[n];

    // 初始化并查集: 每个城市的父节点指向自身，即每个城市自成一个独立的集合
    for (int i = 0; i < n; i++) {
      parent[i] = i;
    }

    // 遍历邻接矩阵，对每个相连的城市对执行合并操作
    // 注意: 只遍历上三角部分(i < j)，避免重复处理，因为矩阵是对称的
    for (int i = 0; i < n; i++) {
      for (int j = i + 1; j < n; j++) {
        // 如果城市i和城市j直接相连，将它们合并到同一个集合
        if (isConnected[i][j] == 1) {
          union(parent, i, j);
        }
      }
    }

    // 统计根节点数量: 找出所有parent[i] == i的城市，它们是各自集合的根节点
    // 根节点的数量就是省份数量
    int count = 0;
    for (int i = 0; i < n; i++) {
      // 如果城市i的父节点是自身，说明它是根节点
      if (find(parent, i) == i) {
        count++;
      }
    }

    // 返回省份数量
    return count;
  }

  /**
   * 查找元素所属集合的根节点，使用路径压缩优化.
   *
   * 路径压缩优化: 在查找过程中，将沿途的每个节点直接连接到根节点，
   * 这样后续查找这些节点时可以直接跳到根节点，减少路径长度。
   *
   * 例如: 假设树的结构是 1 -> 2 -> 3 -> 4 (根节点为4)
   * 第一次find(parent, 1)会将路径压缩为: 1 -> 4, 2 -> 4, 3 -> 4
   * 后再find时，任何节点都能一步到达根节点
   *
   * @param parent 并查集数组，存储每个元素的父节点
   * @param x      要查找根节点的元素索引
   * @return 元素x所属集合的根节点索引
   */
  private int find(int[] parent, int x) {
    // 如果x不是根节点(父节点不是自身)，递归查找根节点
    // 同时进行路径压缩: 将x的父节点直接指向根节点
    if (parent[x] != x) {
      parent[x] = find(parent, parent[x]);
    }
    // 返回根节点
    return parent[x];
  }

  /**
   * 将两个元素合并到同一个集合中.
   *
   * 合并策略: 分别找到两个元素所属集合的根节点，
   * 如果根节点不同，将一个根节点指向另一个根节点，实现集合合并。
   *
   * 注意: 这里使用了简单的合并策略，没有按秩合并。
   * 按秩合并可以进一步优化树的高度，但路径压缩已经能保证近乎常数时间的操作。
   *
   * @param parent 并查集数组，存储每个元素的父节点
   * @param x      第一个元素索引
   * @param y      第二个元素索引
   */
  private void union(int[] parent, int x, int y) {
    // 找到x的根节点
    int rootX = find(parent, x);
    // 找到y的根节点
    int rootY = find(parent, y);

    // 如果根节点不同，说明两个元素在不同的集合中，需要合并
    if (rootX != rootY) {
      // 将y所在集合的根节点rootY指向x所在集合的根节点rootX
      // 合并后，两个集合就变成了一个集合
      parent[rootY] = rootX;
    }
    // 如果根节点相同，说明两个元素已经在同一个集合中，无需操作
  }

}
